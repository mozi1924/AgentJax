/**
 * Generates TypeScript type definitions from JSON Schema files produced by
 * the Rust `gen_schemas` binary.
 *
 * Usage:
 *   cd src-tauri && cargo run --bin gen_schemas
 *   cd .. && node scripts/generate-config-types.mjs
 *
 * Output: src/features/settings/__generated__/config-types.ts
 */

import { readFileSync, writeFileSync, readdirSync, existsSync, mkdirSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, '..');
const SCHEMAS_DIR = join(ROOT, 'gen', 'schemas');
const OUT_DIR = join(ROOT, 'src', 'features', 'settings', '__generated__');
const OUT_FILE = join(OUT_DIR, 'config-types.ts');

// ── Main ────────────────────────────────────────────────────────────────────

function main() {
  if (!existsSync(SCHEMAS_DIR)) {
    console.error(
      `Schema directory not found at ${SCHEMAS_DIR}.\n` +
        'Run `cd src-tauri && cargo run --bin gen_schemas` first.'
    );
    process.exit(1);
  }

  const files = readdirSync(SCHEMAS_DIR)
    .filter((f) => f.endsWith('.json'))
    .sort();

  /** @type {Map<string, any>} */
  const schemas = new Map();
  for (const file of files) {
    const name = file.replace('.json', '');
    const content = JSON.parse(readFileSync(join(SCHEMAS_DIR, file), 'utf-8'));
    schemas.set(name, content);
  }

  const output = generateTypes(schemas);
  mkdirSync(OUT_DIR, { recursive: true });
  writeFileSync(OUT_FILE, output, 'utf-8');
  const counted = output.match(/\bexport (interface|type) \w+/g);
  console.log(`✓ Generated ${OUT_FILE} (${counted ? counted.length : schemas.size} types)`);
}

// ── TypeScript generation ───────────────────────────────────────────────────

/**
 * @param {Map<string, any>} schemas
 * @returns {string}
 */
function generateTypes(schemas) {
  const lines = [
    '// ═══════════════════════════════════════════════════════════════════════',
    '//  auto-generated – do not edit manually',
    '//  source: gen/schemas/*.json  (generated by `cargo run --bin gen_schemas`)',
    '// ═══════════════════════════════════════════════════════════════════════',
    '',
    '// Shared config types used in IPC between Rust backend and React frontend.',
    '',
  ];

  /** @type {Set<string>} Track emitted type names to avoid duplicates. */
  const emitted = new Set();

  for (const [, schema] of schemas) {
    emitType(schema, schemas, lines, emitted);
  }

  lines.push('');
  return lines.join('\n');
}

/**
 * Emit a single schema type (the root object plus any $defs it references).
 * Skips already-emitted type names.
 *
 * @param {any} schema
 * @param {Map<string, any>} allSchemas
 * @param {string[]} lines
 * @param {Set<string>} emitted
 */
function emitType(schema, allSchemas, lines, emitted) {
  // Emit $defs first
  if (schema.$defs) {
    for (const [defName, defSchema] of Object.entries(schema.$defs)) {
      emitInterface(defName, defSchema, allSchemas, lines, emitted);
    }
  }

  const title = schema.title;
  if (title) {
    emitInterface(title, schema, allSchemas, lines, emitted);
  }
}

/**
 * @param {string} name
 * @param {any} schema
 * @param {Map<string, any>} allSchemas
 * @param {string[]} lines
 * @param {Set<string>} emitted
 */
function emitInterface(name, schema, allSchemas, lines, emitted) {
  if (emitted.has(name)) return;
  emitted.add(name);

  // Enum
  if (isEnumSchema(schema)) {
    emitEnum(name, schema, lines);
    return;
  }

  // Object/struct
  if (schema.type === 'object' || schema.properties) {
    emitObjectType(name, schema, allSchemas, lines);
    return;
  }

  // Union / oneOf (primitive type alias)
  if (schema.oneOf) {
    const types = schema.oneOf.map((s) => resolveTypeRef(s, allSchemas));
    lines.push(`export type ${name} = ${types.join(' | ')};`);
    lines.push('');
    return;
  }

  // Fallback: simple type alias
  const tsType = jsonSchemaTypeToTS(schema, allSchemas);
  lines.push(`export type ${name} = ${tsType};`);
  lines.push('');
}

// ── Enum generation ─────────────────────────────────────────────────────────

/**
 * @param {any} schema
 * @returns {boolean}
 */
function isEnumSchema(schema) {
  return (
    (schema.type === 'string' && Array.isArray(schema.enum)) ||
    (schema.oneOf &&
      schema.oneOf.every(
        (s) => s.type === 'string' && Array.isArray(s.enum) && s.enum.length === 1
      ))
  );
}

/**
 * @param {string} name
 * @param {any} schema
 * @param {string[]} lines
 */
function emitEnum(name, schema, lines) {
  const values = schema.enum || schema.oneOf.flatMap((s) => s.enum);
  addJSDoc(schema, lines);
  if (values.length === 1) {
    lines.push(`export type ${name} = '${values[0]}';`);
  } else {
    lines.push(`export type ${name} =`);
    for (const v of values) {
      lines.push(`  | '${v}'`);
    }
    lines.push(';');
  }
  lines.push('');
}

// ── Object generation ───────────────────────────────────────────────────────

/**
 * @param {string} name
 * @param {any} schema
 * @param {Map<string, any>} allSchemas
 * @param {string[]} lines
 */
function emitObjectType(name, schema, allSchemas, lines) {
  addJSDoc(schema, lines);
  lines.push(`export interface ${name} {`);

  // Properties
  if (schema.properties) {
    for (const [propName, propSchema] of Object.entries(schema.properties)) {
      addField(propName, propSchema, schema, allSchemas, lines);
    }
  }

  // Additional properties (map types)
  if (schema.additionalProperties && typeof schema.additionalProperties === 'object') {
    const valueType = resolveTypeRef(schema.additionalProperties, allSchemas);
    lines.push(`  /** Additional custom settings (map). */`);
    lines.push(`  [key: string]: ${valueType};`);
  }

  lines.push('}');
  lines.push('');
}

/**
 * @param {string} propName
 * @param {any} propSchema
 * @param {any} parentSchema
 * @param {Map<string, any>} allSchemas
 * @param {string[]} lines
 */
function addField(propName, propSchema, parentSchema, allSchemas, lines) {
  const isRequired = Array.isArray(parentSchema.required) && parentSchema.required.includes(propName);
  const tsType = resolveTypeRef(propSchema, allSchemas);
  const optional = isRequired ? '' : '?';

  addJSDoc(propSchema, lines);

  // Add default value hint
  if (propSchema.default !== undefined) {
    const defaultStr = JSON.stringify(propSchema.default);
    lines.push(`  // default: ${defaultStr}`);
  }

  // Use the serialized field name as-is from JSON Schema.
  // schemars already respects #[serde(rename_all)] attributes, so the
  // field names in the schema match what the actual JSON uses.
  lines.push(`  ${propName}${optional}: ${tsType};`);
  lines.push('');
}

// ── Type resolution ─────────────────────────────────────────────────────────

/**
 * @param {any} schema
 * @param {Map<string, any>} allSchemas
 * @returns {string}
 */
function resolveTypeRef(schema, allSchemas) {
  if (!schema || typeof schema !== 'object') return 'unknown';

  // $ref
  if (schema.$ref) {
    const refName = schema.$ref.replace('#/$defs/', '');
    return refName;
  }

  // const value (literal type)
  if (schema.const !== undefined) {
    return JSON.stringify(schema.const);
  }

  // enum
  if (schema.enum) {
    return schema.enum.map((v) => `'${v}'`).join(' | ');
  }

  // oneOf
  if (schema.oneOf) {
    return schema.oneOf.map((s) => resolveTypeRef(s, allSchemas)).join(' | ');
  }

  // null
  if (schema.type === 'null') return 'null';

  // Array with nullable types like ["string", "null"]
  if (Array.isArray(schema.type)) {
    return schema.type.map((t) => {
      if (t === 'null') return 'null';
      return jsonSchemaPrimitive(t, schema);
    }).join(' | ');
  }

  // Basic type
  return jsonSchemaTypeToTS(schema, allSchemas);
}

/**
 * Maps JSON Schema types → TypeScript types.
 *
 * @param {any} schema
 * @param {Map<string, any>} allSchemas
 * @returns {string}
 */
function jsonSchemaTypeToTS(schema, allSchemas) {
  if (!schema || typeof schema !== 'object') return 'unknown';

  const type = schema.type;

  switch (type) {
    case 'string':
      return 'string';
    case 'boolean':
      return 'boolean';
    case 'integer':
    case 'number':
      return 'number';
    case 'array': {
      const items = schema.items;
      if (items) {
        const itemType = resolveTypeRef(items, allSchemas);
        return `${itemType}[]`;
      }
      return 'unknown[]';
    }
    case 'object': {
      if (schema.additionalProperties) {
        const valType = resolveTypeRef(schema.additionalProperties, allSchemas);
        return `Record<string, ${valType}>`;
      }
      return 'Record<string, unknown>';
    }
    default:
      return 'unknown';
  }
}

/**
 * @param {string} type
 * @param {any} schema
 * @returns {string}
 */
function jsonSchemaPrimitive(type, _schema) {
  switch (type) {
    case 'string': return 'string';
    case 'boolean': return 'boolean';
    case 'integer':
    case 'number': return 'number';
    default: return 'unknown';
  }
}

// ── Helpers ─────────────────────────────────────────────────────────────────

/**
 * @param {any} schema
 * @param {string[]} lines
 */
function addJSDoc(schema, lines) {
  if (schema.description) {
    for (const line of schema.description.split('\n')) {
      lines.push(`  /** ${line} */`);
    }
  }
}

// ── Run ─────────────────────────────────────────────────────────────────────

main();
